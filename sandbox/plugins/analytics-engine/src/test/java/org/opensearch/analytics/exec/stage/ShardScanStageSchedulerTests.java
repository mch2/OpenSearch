/**
 * Focused unit tests for {@link ShardScanStageScheduler} — the scheduler
 * for row-producing DATA_NODE stages.
 *
 * <p>Post Change 1: tests call {@code createExecution()} and verify the
 * returned {@link StageExecution} instance (type, initial state, captured
 * dependencies). Child-walking tests have moved to PlanWalker tests since
 * the scheduler no longer handles children.
 *
 * Validates: Requirements 2.5, 3.3
 */
@SuppressWarnings("unchecked")
public class ShardScanStageSchedulerTests extends OpenSearchTestCase {

    private RelDataTypeFactory typeFactory;
    private RelOptCluster cluster;
    private RelDataType rowType;

    @Override
    public void setUp() throws Exception {
        super.setUp();
        typeFactory = new JavaTypeFactoryImpl();
        RexBuilder rexBuilder = new RexBuilder(typeFactory);
        HepPlanner planner = new HepPlanner(new HepProgramBuilder().build());
        cluster = RelOptCluster.create(planner, rexBuilder);
        rowType = typeFactory.builder().add("field_0", SqlTypeName.VARCHAR).build();
    }

    // ─── Helpers ────────────────────────────────────────────────────────

    private OpenSearchTableScan buildTableScan(String tableName, List<String> viableBackends) {
        RelOptTable table = mock(RelOptTable.class);
        when(table.getQualifiedName()).thenReturn(List.of("default", tableName));
        when(table.getRowType()).thenReturn(rowType);
        return new OpenSearchTableScan(cluster, RelTraitSet.createEmpty(), table, viableBackends, List.of());
    }

    private ClusterService buildMockClusterService(String tableName, int numShards) {
        Index index = new Index(tableName, "_na_");

        ClusterState clusterState = mock(ClusterState.class);
        DiscoveryNodes discoveryNodes = mock(DiscoveryNodes.class);
        for (int i = 0; i < numShards; i++) {
            DiscoveryNode node = mock(DiscoveryNode.class);
            when(node.getId()).thenReturn("node_" + i);
            when(discoveryNodes.get("node_" + i)).thenReturn(node);
        }
        when(clusterState.nodes()).thenReturn(discoveryNodes);

        List<ShardIterator> iterators = new ArrayList<>();
        for (int i = 0; i < numShards; i++) {
            ShardIterator shardIt = mock(ShardIterator.class);
            ShardRouting shard = mock(ShardRouting.class);
            when(shard.shardId()).thenReturn(new ShardId(index, i));
            when(shard.currentNodeId()).thenReturn("node_" + i);
            when(shardIt.nextOrNull()).thenReturn(shard);
            iterators.add(shardIt);
        }
        GroupShardsIterator<ShardIterator> groupIterator = new GroupShardsIterator<>(iterators);

        OperationRouting operationRouting = mock(OperationRouting.class);
        when(operationRouting.searchShards(any(), eq(new String[] { tableName }), isNull(), isNull())).thenReturn(groupIterator);

        ClusterService clusterService = mock(ClusterService.class);
        when(clusterService.state()).thenReturn(clusterState);
        when(clusterService.operationRouting()).thenReturn(operationRouting);

        return clusterService;
    }

    private AnalyticsSearchTransportService immediateRowDispatcher(ClusterService clusterService) {
        return new AnalyticsSearchTransportService(mock(TransportService.class), clusterService) {
            @Override
            public void dispatchFragment(
                FragmentExecutionRequest request,
                DiscoveryNode node,
                StreamingResponseListener<FragmentExecutionResponse> listener,
                Task parentTask,
                PendingExecutions _pending
            ) {
                List<Object[]> rows = new ArrayList<>();
                rows.add(new Object[] { "row_" + request.getShardId().id() });
                listener.onStreamResponse(MockFragmentResponse.create(List.of("field_0"), rows), true);
            }
        };
    }

    // ─── testCreateExecutionReturnsShardScanStageExecution ──────────────

    public void testCreateExecutionReturnsShardScanStageExecution() {
        int numShards = 2;
        ClusterService clusterService = buildMockClusterService("http_logs", numShards);
        AnalyticsSearchTransportService dispatcher = immediateRowDispatcher(clusterService);
        ShardScanStageScheduler scheduler = new ShardScanStageScheduler(clusterService, dispatcher);

        OpenSearchTableScan scan = buildTableScan("http_logs", List.of("lucene"));
        Stage stage = new Stage(0, scan, List.of(), null);
        stage.setPlanAlternatives(List.of(new StagePlan(scan, "lucene")));

        QueryContext config = QueryContext.forTest("test-query", null);

        StageExecution exec = scheduler.createExecution(stage, new RowProducingSink(), config);

        assertNotNull("createExecution should return a non-null execution", exec);
        assertTrue(
            "Should return ShardScanStageExecution, got: " + exec.getClass().getSimpleName(),
            exec instanceof ShardScanStageExecution
        );
        assertEquals("Initial state should be CREATED", StageExecution.State.CREATED, exec.getState());
        assertEquals("Stage id should match", 0, exec.getStageId());
    }

    // ─── testCreateExecutionThenStartDispatchesAndCompletes ─────────────

    public void testCreateExecutionThenStartDispatchesAndCompletes() {
        int numShards = 2;
        ClusterService clusterService = buildMockClusterService("http_logs", numShards);
        AnalyticsSearchTransportService dispatcher = immediateRowDispatcher(clusterService);
        ShardScanStageScheduler scheduler = new ShardScanStageScheduler(clusterService, dispatcher);

        OpenSearchTableScan scan = buildTableScan("http_logs", List.of("lucene"));
        Stage stage = new Stage(0, scan, List.of(), null);
        stage.setPlanAlternatives(List.of(new StagePlan(scan, "lucene")));

        QueryContext config = QueryContext.forTest("test-query", null);
        RowProducingSink outputSink = new RowProducingSink();

        StageExecution exec = scheduler.createExecution(stage, outputSink, config);
        assertNotNull("createExecution should return a non-null execution", exec);

        exec.start();

        assertEquals("State should be SUCCEEDED after start", StageExecution.State.SUCCEEDED, exec.getState());
        assertTrue("Rows should have been fed to the outputSink", outputSink.getRowCount() > 0);
    }

    // Parent-type validation has moved to StageExecutionBuilder (see
    // StageExecutionBuilderRoutingTests#testBuildExecutionRejectsNonRowReceivingParent).
    // The scheduler itself no longer performs instanceof checks — it takes a
    // pre-resolved ExchangeSink and does not see the parent execution.
}

