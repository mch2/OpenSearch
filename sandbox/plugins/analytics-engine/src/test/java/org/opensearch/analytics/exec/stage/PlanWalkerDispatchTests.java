/**
 * Tests that {@link PlanWalker} looks up execution construction via
 * {@link StageExecutionBuilder#buildExecution} and
 * {@link StageExecutionBuilder#buildExecution} during the up-front walk.
 *
 * <p>Validates: Requirements 1.1, 1.2
 */
public class PlanWalkerDispatchTests extends OpenSearchTestCase {

    private RelOptCluster cluster;
    private RelDataType rowType;

    @Override
    public void setUp() throws Exception {
        super.setUp();
        RelDataTypeFactory typeFactory = new JavaTypeFactoryImpl();
        RexBuilder rexBuilder = new RexBuilder(typeFactory);
        HepPlanner planner = new HepPlanner(new HepProgramBuilder().build());
        cluster = RelOptCluster.create(planner, rexBuilder);
        rowType = typeFactory.builder().add("field_0", SqlTypeName.VARCHAR).build();
    }

    private static AnalyticsSearchTransportService failingDispatcher() {
        return new AnalyticsSearchTransportService(mock(TransportService.class), mock(ClusterService.class)) {
            @Override
            public void dispatchFragment(FragmentExecutionRequest r, DiscoveryNode n, StreamingResponseListener<FragmentExecutionResponse> l, Task t, PendingExecutions p) {
                fail("should not be called");
            }
        };
    }

    // ─── Task 11: testDispatchStageCallsStageExecutorBuild ──────────────

    /**
     * Spy {@link StageExecutionBuilder} via a subclass that tracks
     * {@code buildExecution} calls. Verify it is called during the
     * up-front walk for a single-stage DAG.
     *
     * Validates: Requirements 1.1
     */
    public void testDispatchStageCallsStageExecutorBuildRoot() {
        int numShards = 1;
        ClusterService clusterService = buildMockClusterService("test_table", numShards);

        AtomicBoolean buildRootCalled = new AtomicBoolean(false);
        AtomicReference<Stage> capturedStage = new AtomicReference<>();
        AtomicReference<QueryContext> capturedConfig = new AtomicReference<>();

        AnalyticsSearchTransportService dispatcher = failingDispatcher();
        StageExecutionBuilder executor = new StageExecutionBuilder(clusterService, dispatcher, null) {
            @Override
            public StageExecution buildRootExecution(Stage rootStage, QueryContext cfg) {
                buildRootCalled.set(true);
                capturedStage.set(rootStage);
                capturedConfig.set(cfg);
                return new PassThroughStageExecution(rootStage, new org.opensearch.analytics.exec.RowProducingSink());
            }
        };

        Stage stage = new Stage(0, null, List.of(), null, StageExecutionType.DATA_NODE);
        QueryDAG dag = new QueryDAG("test-query", stage);

        QueryContext config = QueryContext.forTest(dag, null);

        AtomicBoolean success = new AtomicBoolean(false);
        new QueryScheduler(executor).execute(
            config,
            ActionListener.wrap(v -> success.set(true), e -> fail("unexpected: " + e))
        );

        assertTrue("buildRootExecution should have been called", buildRootCalled.get());
        assertSame("Stage should pass through unchanged", stage, capturedStage.get());
        assertSame("Config should pass through unchanged", config, capturedConfig.get());
    }

    // ─── Task 12: testDispatchInvokesBuildWithCorrectArgs ────────────────

    /**
     * Verify the StageExecutionBuilder's build method is invoked with the correct
     * arguments during the up-front walk.
     *
     * Validates: Requirements 1.1
     */
    public void testDispatchStageInvokesBuildExecutionDirectlyWithCorrectArgs() {
        ClusterService clusterService = mock(ClusterService.class);

        AtomicBoolean called = new AtomicBoolean(false);
        AtomicReference<Stage> capturedStage = new AtomicReference<>();
        AtomicReference<QueryContext> capturedConfig = new AtomicReference<>();

        AnalyticsSearchTransportService dispatcher = failingDispatcher();
        StageExecutionBuilder executor = new StageExecutionBuilder(clusterService, dispatcher, null) {
            @Override
            public StageExecution buildRootExecution(Stage rootStage, QueryContext cfg) {
                called.set(true);
                capturedStage.set(rootStage);
                capturedConfig.set(cfg);
                return new PassThroughStageExecution(rootStage, new org.opensearch.analytics.exec.RowProducingSink());
            }
        };

        Stage stage = new Stage(0, null, List.of(), null, StageExecutionType.DATA_NODE);
        QueryDAG dag = new QueryDAG("test-query", stage);

        QueryContext config = QueryContext.forTest(dag, null);

        AtomicBoolean success = new AtomicBoolean(false);
        new QueryScheduler(executor).execute(
            config,
            ActionListener.wrap(v -> success.set(true), e -> fail("unexpected: " + e))
        );

        assertTrue("buildRootExecution should have been called", called.get());
        assertSame("Stage should pass through unchanged", stage, capturedStage.get());
        assertSame("Config should pass through unchanged", config, capturedConfig.get());
    }

    // ─── Task 13: testPassThroughStillWorksAfterSplit ────────────────────

    /**
     * For a pass-through LOCAL stage (fragment is StageInputScan), verify
     * that the pass-through path in {@link LocalStageScheduler} still works
     * correctly via {@link StageExecutionBuilder#buildExecution}.
     *
     * Validates: Requirements 1.1
     */
    public void testPassThroughStillWorksAfterSplit() {
        int numShards = 1;
        ClusterService clusterService = buildMockClusterService("test_table", numShards);

        // Child: data-node stage
        OpenSearchTableScan scan = buildTableScan("test_table");
        ExchangeInfo singletonExchange = new ExchangeInfo(RelDistribution.Type.SINGLETON, null, List.of());
        Stage childStage = new Stage(0, scan, List.of(), singletonExchange);
        childStage.setPlanAlternatives(List.of(new StagePlan(scan, "lucene")));

        // Root: pass-through LOCAL stage (StageInputScan fragment)
        OpenSearchStageInputScan stageInput = new OpenSearchStageInputScan(
            cluster,
            RelTraitSet.createEmpty(),
            0,
            rowType,
            List.of("lucene")
        );
        Stage rootStage = new Stage(1, stageInput, List.of(childStage), null);
        rootStage.setPlanAlternatives(List.of(new StagePlan(stageInput, "lucene")));

        QueryDAG dag = new QueryDAG("test-query", rootStage);

        QueryContext config = QueryContext.forTest(dag, null);

        AnalyticsSearchTransportService dispatcher = new AnalyticsSearchTransportService(mock(TransportService.class), clusterService) {
            @Override
            public void dispatchFragment(FragmentExecutionRequest r, DiscoveryNode n, StreamingResponseListener<FragmentExecutionResponse> l, Task t, PendingExecutions p) {
                List<Object[]> rows = new ArrayList<>();
                rows.add(new Object[] { "v" });
                l.onStreamResponse(MockFragmentResponse.create(List.of("field_0"), rows), true);
            }
        };

        AtomicBoolean success = new AtomicBoolean(false);
        AtomicReference<Iterable<Object[]>> resultRef = new AtomicReference<>();
        new QueryScheduler(
            new StageExecutionBuilder(clusterService, dispatcher, null)
        ).execute(config, ActionListener.wrap(v -> {
            success.set(true);
            resultRef.set(v);
        }, e -> fail("unexpected: " + e)));

        assertTrue("Walk should have succeeded for pass-through stage", success.get());
        List<Object[]> resultList = new ArrayList<>();
        resultRef.get().forEach(resultList::add);
        assertEquals("Result should have rows from child", numShards, resultList.size());
    }

    // ─── Helpers ────────────────────────────────────────────────────────

    private OpenSearchTableScan buildTableScan(String tableName) {
        RelOptTable table = mock(RelOptTable.class);
        when(table.getQualifiedName()).thenReturn(List.of("default", tableName));
        when(table.getRowType()).thenReturn(rowType);
        return new OpenSearchTableScan(cluster, RelTraitSet.createEmpty(), table, List.of("lucene"), List.of());
    }

    private ClusterService buildMockClusterService(String tableName, int numShards) {
        Index index = new Index(tableName, "_na_");
        ClusterState clusterState = mock(ClusterState.class);
        DiscoveryNodes discoveryNodes = mock(DiscoveryNodes.class);
        for (int i = 0; i < numShards; i++) {
            DiscoveryNode node = mock(DiscoveryNode.class);
            when(node.getId()).thenReturn("node_" + i);
            when(discoveryNodes.get("node_" + i)).thenReturn(node);
        }
        when(clusterState.nodes()).thenReturn(discoveryNodes);

        List<ShardIterator> iterators = new ArrayList<>();
        for (int i = 0; i < numShards; i++) {
            ShardIterator shardIt = mock(ShardIterator.class);
            ShardRouting shard = mock(ShardRouting.class);
            when(shard.shardId()).thenReturn(new ShardId(index, i));
            when(shard.currentNodeId()).thenReturn("node_" + i);
            when(shardIt.nextOrNull()).thenReturn(shard);
            iterators.add(shardIt);
        }
        GroupShardsIterator<ShardIterator> groupIterator = new GroupShardsIterator<>(iterators);

        OperationRouting operationRouting = mock(OperationRouting.class);
        when(operationRouting.searchShards(any(), eq(new String[] { tableName }), isNull(), isNull())).thenReturn(groupIterator);

        ClusterService clusterService = mock(ClusterService.class);
        when(clusterService.state()).thenReturn(clusterState);
        when(clusterService.operationRouting()).thenReturn(operationRouting);
        return clusterService;
    }
}

