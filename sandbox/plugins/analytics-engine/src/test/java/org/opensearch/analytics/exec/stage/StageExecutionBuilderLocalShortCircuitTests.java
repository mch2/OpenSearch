import java.util.List;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.concurrent.atomic.AtomicReference;

import static org.mockito.Mockito.mock;

/**
 * Tests that pass-through LOCAL stages are handled by
 * {@link PlanWalker} via the event-driven driver (pass-through detection
 * is in {@link LocalStageScheduler}).
 *
 * Validates: Requirements 1.6
 */
public class StageExecutionBuilderLocalShortCircuitTests extends OpenSearchTestCase {

    private static AnalyticsSearchTransportService failingDispatcher() {
        return new AnalyticsSearchTransportService(mock(TransportService.class), mock(ClusterService.class)) {
            @Override
            public void dispatchFragment(FragmentExecutionRequest r, DiscoveryNode n, StreamingResponseListener<FragmentExecutionResponse> l, Task t, PendingExecutions p) {
                fail("should not be called");
            }
        };
    }

    /**
     * A LOCAL pass-through stage with no children should complete immediately
     * via PlanWalker's event-driven path. The PassThroughStageExecution
     * transitions to SUCCEEDED and the terminal listener fires.
     */
    public void testLocalStageWithEmptyChildrenSucceeds() {
        ClusterService clusterService = mock(ClusterService.class);
        AnalyticsSearchTransportService dispatcher = failingDispatcher();
        StageExecutionBuilder executor = new StageExecutionBuilder(clusterService, dispatcher, null);

        // Build a LOCAL pass-through stage with no children (null fragment = pass-through)
        Stage stage = new Stage(0, null, List.of(), null, StageExecutionType.LOCAL);

        AtomicBoolean responseCalled = new AtomicBoolean(false);
        AtomicReference<Exception> failureRef = new AtomicReference<>();

        QueryDAG dag = new QueryDAG("test-query", stage);
        QueryContext config = QueryContext.forTest(dag, null);
        new QueryScheduler(executor).execute(
            config,
            ActionListener.wrap(v -> responseCalled.set(true), failureRef::set)
        );

        assertTrue("listener.onResponse should have been called", responseCalled.get());
        assertNull("listener.onFailure should not have been called", failureRef.get());
    }

    /**
     * A LOCAL pass-through stage WITH children should handle children
     * via PlanWalker's event-driven path. The pass-through root waits
     * for children to succeed before transitioning itself.
     */
    public void testLocalStageWithChildrenDoesNotShortCircuit() {
        ClusterService clusterService = mock(ClusterService.class);
        AnalyticsSearchTransportService dispatcher = failingDispatcher();

        // Use a spy executor that returns a PassThroughStageExecution for both root and child.
        // The root arrives with parentExec == PassThroughStageExecution (supplies the root sink); children
        // arrive with parentExec == the real pass-through root.
        StageExecutionBuilder executor = new StageExecutionBuilder(clusterService, dispatcher, null) {
            @Override
            public StageExecution buildExecution(Stage stage, StageExecution parentExec, QueryContext cfg) {
                if (parentExec instanceof PassThroughStageExecution holder) {
                    return new PassThroughStageExecution(stage, holder.sink(stage.getStageId()));
                }
                return new PassThroughStageExecution(stage, new RowProducingSink());
            }
        };

        // LOCAL pass-through stage with one child (null fragment = pass-through)
        Stage child = new Stage(1, null, List.of(), null, StageExecutionType.DATA_NODE);
        Stage stage = new Stage(0, null, List.of(child), null, StageExecutionType.LOCAL);

        AtomicBoolean responseCalled = new AtomicBoolean(false);

        QueryDAG dag = new QueryDAG("test-query", stage);
        QueryContext config = QueryContext.forTest(dag, null);
        new QueryScheduler(executor).execute(
            config,
            ActionListener.wrap(v -> responseCalled.set(true), e -> {})
        );

        // The pass-through root should have completed after its child
        assertTrue("listener.onResponse should have been called", responseCalled.get());
    }
}

